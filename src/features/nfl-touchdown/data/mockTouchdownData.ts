/**
 * TDPI (Touchdown Probability Index) Telemetry Formula:
 * TDPI = w1(RZ_Touch_Share) + w2(Inside_10_Volume) + w3(Opp_Def_RZ_Vulnerability) + w4(Implied_Team_Total) + w5(Game_Script_Leverage)
 *
 * w1 = 30%: Red Zone Touch Share (0-100)
 * w2 = 25%: Inside-10 High-Value Touches (volume scaled to 0-100)
 * w3 = 20%: Opponent RZ Defensive Vulnerability (rank 1-32 scaled, higher rank = more porous)
 * w4 = 15%: Implied Team Scoring Total (points normalized)
 * w5 = 10%: Game Script & Pace Leverage (goal-line snap & pace rate)
 */
export function calculateTDPI(metrics: {
  rzTouchShare: number;
  inside10Touches: number;
  oppRzDefRank: number;
  impliedTeamTotal: number;
  goalLineSnapPercent?: number;
}): number {
  const w1 = 0.30;
  const w2 = 0.25;
  const w3 = 0.20;
  const w4 = 0.15;
  const w5 = 0.10;

  const rzShareNorm = Math.min(100, Math.max(0, metrics.rzTouchShare));
  const inside10Norm = Math.min(100, Math.max(0, (metrics.inside10Touches / 16) * 100));
  const oppDefNorm = Math.min(100, Math.max(0, (metrics.oppRzDefRank / 32) * 100));
  const impliedNorm = Math.min(100, Math.max(0, (metrics.impliedTeamTotal / 32) * 100));
  const scriptNorm = Math.min(100, Math.max(0, metrics.goalLineSnapPercent ?? 75));

  const score = (w1 * rzShareNorm) + (w2 * inside10Norm) + (w3 * oppDefNorm) + (w4 * impliedNorm) + (w5 * scriptNorm);
  return Math.round(score * 10) / 10;
}

export function determineTier(tdpi: number): PlayerTier {
  if (tdpi >= 80) return 'ELITE';
  if (tdpi >= 65) return 'STRONG';
  if (tdpi >= 50) return 'VALUE';
  return 'SLEEPER';
}

